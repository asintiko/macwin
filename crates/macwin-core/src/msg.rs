//! Domain messages exchanged between two macwin peers.
//!
//! These are the decoded, validated forms; `macwin-proto` owns the wire
//! encoding. Channel placement:
//! - control stream: session-level traffic (Hello, Heartbeat, Ping/Pong);
//! - input stream: everything that must be totally ordered per direction
//!   (Enter -> ModifierSync -> keys/buttons/wheel -> Leave, TakeControl);
//! - datagrams: latest-wins cursor positions (`MouseAbs`);
//! - clipboard streams: one unidirectional stream per [`ClipboardMsg`], so
//!   a large text never delays heartbeats or input.
//!
//! `Ping`/`Pong` are accepted on every channel and answered on the channel
//! they arrived on. Pairing ([`PairMsg`]) runs on its own connection.

use std::fmt;

use crate::arrange::Placement;
use crate::types::{
    Hid, ModifierMask, MouseButton, Os, Point, RoleKind, ScreenInfo, Side, WheelUnit,
};

/// The sender can control the receiver (it captures and forwards input).
pub const CAP_INPUT_CAPTURE: &str = "input.capture";
/// The sender can be controlled (it injects input).
pub const CAP_INPUT_INJECT: &str = "input.inject";
/// The sender runs the `spike net` latency tool.
pub const CAP_SPIKE_NET: &str = "spike.net";
/// The sender sends and accepts plain-text clipboard updates.
pub const CAP_CLIPBOARD_TEXT: &str = "clipboard.text";
/// The sender sends and accepts clipboard images (PNG).
pub const CAP_CLIPBOARD_IMAGE: &str = "clipboard.image";
/// The sender sends and accepts copied files.
pub const CAP_CLIPBOARD_FILES: &str = "clipboard.files";
/// The sender injects pixel wheel deltas (smooth scrolling); peers without
/// it get whole-notch units instead.
pub const CAP_WHEEL_PIXEL: &str = "input.wheel-pixel";

/// Messages on the control stream.
#[derive(Debug, Clone, PartialEq)]
pub enum ControlMsg {
    Hello(Hello),
    Heartbeat(Heartbeat),
    Ping(Ping),
    Pong(Pong),
}

/// Messages on the input stream.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum InputMsg {
    Enter(Enter),
    Leave(Leave),
    TakeControl(TakeControl),
    Key(KeyMsg),
    Button(ButtonMsg),
    Wheel(WheelMsg),
    ModifierSync(ModifierMask),
    Ping(Ping),
    Pong(Pong),
}

/// Messages sent as QUIC datagrams.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum DatagramMsg {
    MouseAbs(MouseAbs),
    Ping(Ping),
    Pong(Pong),
}

/// First message on the control stream, sent by both sides.
#[derive(Debug, Clone, PartialEq)]
pub struct Hello {
    /// `major << 16 | minor`.
    pub protocol_version: u32,
    pub capabilities: Vec<String>,
    pub os: Os,
    pub os_version: String,
    pub device_name: String,
    /// The sender's screens in its native coordinates.
    pub screens: Vec<ScreenInfo>,
    /// The sender's configured "peer is to my left/right", if any (legacy,
    /// informational: `placement` supersedes it).
    pub peer_side: Option<Side>,
    /// Where the sender placed the receiver's screens next to its own (sent
    /// by the primary computer).
    pub placement: Option<Placement>,
    pub agent_version: String,
}

impl Hello {
    pub fn has_capability(&self, cap: &str) -> bool {
        self.capabilities.iter().any(|c| c == cap)
    }
}

/// Periodic liveness proof generated by the sender's Engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Heartbeat {
    /// The epoch of the sender's current role (or its highest known epoch
    /// while Idle).
    pub epoch: u64,
    pub role: RoleKind,
}

/// Round-trip probe. `sent_micros` is the sender's own monotonic clock, so no
/// clock synchronisation is needed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Ping {
    pub id: u64,
    pub sent_micros: u64,
}

/// Answer to a [`Ping`], echoing its fields.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pong {
    pub id: u64,
    pub ping_sent_micros: u64,
}

/// The sender starts controlling the receiver.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Enter {
    pub epoch: u64,
    /// Virtual cursor start in the receiver's native coordinates.
    pub at: Point,
}

/// The sender stops controlling the receiver.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Leave {
    pub epoch: u64,
}

/// The sender (currently controlled) saw physical input and takes control
/// back.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TakeControl {
    pub epoch: u64,
}

/// A forwarded key (already remapped by the controller).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KeyMsg {
    pub hid: Hid,
    pub down: bool,
    pub repeat: bool,
}

/// A forwarded mouse button at the virtual cursor position.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ButtonMsg {
    pub button: MouseButton,
    pub down: bool,
    pub at: Point,
}

/// A forwarded wheel event.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WheelMsg {
    pub dx: i32,
    pub dy: i32,
    pub unit: WheelUnit,
}

/// Latest-wins absolute cursor position in the receiver's native space.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MouseAbs {
    pub epoch: u64,
    pub seq: u64,
    pub at: Point,
}

/// Messages on clipboard streams (exactly one per unidirectional stream).
/// Copied files travel separately, as a [`FilesHeader`] followed by their
/// data on a stream of their own.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipboardMsg {
    Text(ClipboardText),
    Image(ClipboardImage),
    /// The sender's clipboard changed to something macwin does not share
    /// (a password, too much data, a kind the receiver does not accept).
    /// Carries no content.
    Other {
        clock: u64,
    },
}

impl ClipboardMsg {
    pub fn clock(&self) -> u64 {
        match self {
            ClipboardMsg::Text(t) => t.clock,
            ClipboardMsg::Image(i) => i.clock,
            ClipboardMsg::Other { clock } => *clock,
        }
    }
}

/// The sender's clipboard now holds an image.
#[derive(Clone, PartialEq, Eq)]
pub struct ClipboardImage {
    pub clock: u64,
    /// PNG-encoded.
    pub png: Vec<u8>,
}

/// Never prints the content, only its size.
impl fmt::Debug for ClipboardImage {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ClipboardImage")
            .field("clock", &self.clock)
            .field("bytes", &self.png.len())
            .finish()
    }
}

/// First frame of a files stream: what follows, in order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FilesHeader {
    /// Lamport clock of the clipboard change (see [`crate::clipboard`]).
    pub clock: u64,
    pub entries: Vec<FileEntry>,
}

impl FilesHeader {
    /// Bytes of file data that follow the header.
    pub fn total_bytes(&self) -> u64 {
        self.entries
            .iter()
            .fold(0u64, |acc, e| acc.saturating_add(e.size))
    }
}

/// One file or directory of a transfer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileEntry {
    /// Relative, `/`-separated; the first component is a top-level item.
    pub path: String,
    /// Bytes of data that follow for this entry (0 for directories).
    pub size: u64,
    pub dir: bool,
    /// The source had an execute bit (Unix).
    pub executable: bool,
    /// Modification time in milliseconds since the Unix epoch, 0 if unknown.
    pub mtime_ms: i64,
}

/// The sender's clipboard now holds `text`.
#[derive(Clone, PartialEq, Eq)]
pub struct ClipboardText {
    /// Lamport clock of the change; orders concurrent updates (see
    /// [`crate::clipboard`]).
    pub clock: u64,
    pub text: String,
}

/// Never prints the content, only its size.
impl fmt::Debug for ClipboardText {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ClipboardText")
            .field("clock", &self.clock)
            .field("bytes", &self.text.len())
            .finish()
    }
}

/// Messages of the pairing exchange (ALPN `macwin-pair/1`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PairMsg {
    Hello(PairHello),
    Confirm(PairConfirm),
    /// The dialer verified the listener's confirmation and saved the pairing.
    Done,
}

/// First pairing message, sent by both sides.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PairHello {
    /// `major << 16 | minor`.
    pub protocol_version: u32,
    pub os: Os,
    pub device_name: String,
    pub agent_version: String,
    /// The sender's "my peer is to my left/right", if the user chose it.
    pub peer_side: Option<Side>,
    /// The sender's SPAKE2 message.
    pub spake: Vec<u8>,
}

/// Key confirmation: an HMAC over the pairing transcript.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PairConfirm {
    pub mac: [u8; 32],
}

/// LAN discovery datagrams (UDP broadcast, see `macwin-net`): finding a
/// machine that waits for pairing, or the paired peer after its address
/// changed. Answers are only hints: pairing is authenticated by the code
/// and sessions by certificate pinning.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DiscoveryMsg {
    Query(DiscoveryQuery),
    Answer(DiscoveryAnswer),
}

/// A broadcast question.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DiscoveryQuery {
    /// `major << 16 | minor`.
    pub protocol_version: u32,
    /// Random per query; answers echo it.
    pub nonce: [u8; 16],
    pub seek: DiscoverySeek,
}

/// What a query looks for.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DiscoverySeek {
    /// Any machine waiting for pairing.
    Pairing,
    /// A paired machine, named by tags over the nonce and the fingerprints
    /// of the wanted (`target`) and the asking (`sender`) machine, so the
    /// fingerprints themselves are never broadcast.
    Peer { target: [u8; 32], sender: [u8; 32] },
}

/// A unicast reply to a query.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DiscoveryAnswer {
    pub protocol_version: u32,
    /// The query's nonce.
    pub nonce: [u8; 16],
    /// The port the machine accepts QUIC connections on; its address is the
    /// answer's source address.
    pub port: u16,
    pub offer: DiscoveryOffer,
}

/// What an answering machine offers.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DiscoveryOffer {
    /// It waits for pairing.
    Pairing {
        os: Os,
        device_name: String,
        fingerprint: [u8; 32],
    },
    /// It runs sessions for the asking machine; `proof` is a tag over the
    /// nonce and the answering machine's fingerprint.
    Peer { proof: [u8; 32] },
}
